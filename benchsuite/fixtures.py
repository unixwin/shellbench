"""Host-side fixture generators for case input files.

A fixture whose content starts with ``@gen:`` is generated by Python before
timing starts, so data-ladder cases don't pay generation cost inside the
timed region. Supported forms:

- ``@gen:lines:N``  -- N numbered text lines ("line 42 lorem ipsum ...")
- ``@gen:words:N``  -- N lines of 8 short words (grep/sort fodder)
- ``@gen:kv:N``     -- N ``key<i>=value<i>`` lines
- ``@gen:csv:N``    -- N CSV rows of 6 columns
- ``@gen:path:N``   -- N relative file paths (glob/sort fodder, as text)
"""

from __future__ import annotations

_WORDS = ("alpha bravo charlie delta echo foxtrot golf hotel india juliet "
          "kilo lima mike november oscar papa quebec romeo sierra tango")


def generate(spec: str) -> str:
    kind, _, arg = spec[5:].partition(":")
    n = int(arg)
    if kind == "lines":
        return "".join("line %d lorem ipsum dolor sit amet %d\n" % (i, i * 7 % 997)
                       for i in range(n))
    if kind == "words":
        w = _WORDS.split()
        return "".join(" ".join(w[(i + j) % len(w)] for j in range(8)) + "\n"
                       for i in range(n))
    if kind == "kv":
        return "".join("key%d=value%d\n" % (i, i) for i in range(n))
    if kind == "csv":
        return "".join("%d,field%d,3.14,item-%d,active,%d\n" % (i, i, i, i % 50)
                       for i in range(n))
    if kind == "path":
        return "".join("dir%d/sub%d/file_%d.txt\n" % (i % 97, i % 13, i)
                       for i in range(n))
    raise ValueError("unknown fixture generator: %r" % spec)


def materialize(content: str) -> str:
    if content.startswith("@gen:"):
        return generate(content)
    return content
