"""Parser throughput: `shell -n` over generated corpora (pure parse cost),
plus parse-adjacent execution shapes. Corpus text is generated by compact
Python builders below -- thousands of script lines from tens of lines of
generator code."""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from benchsuite.model import Case  # noqa: E402


def _simple(n):
    return "\n".join("echo value_%d >/dev/null" % i for i in range(n)) + "\n"


def _funcs(n):
    return "\n".join(
        "f%d() { local x=%d; y=$((x * 2)); echo $y; }" % (i, i)
        for i in range(n)) + "\n"


def _control(n):
    out = []
    for i in range(n // 5):
        out.append("if [ $a -eq %d ]; then echo a; elif [ $a -gt 3 ]; "
                   "then echo b; else echo c; fi" % i)
        out.append("for v in 1 2 3; do case $v in 1) echo one;; 2) echo "
                   "two;; *) echo other;; esac; done")
        out.append("while [ $i -lt 10 ]; do i=$((i+1)); done")
        out.append("x=$(( (1 + 2) * (3 - 4) / (5 %% 3) ))")
        out.append("printf '%%s %%d\\n' name %d >/dev/null" % i)
    return "\n".join(out) + "\n"


def _expand(n):
    out = []
    tmpl = ("x${i}=${{v:-def{i}}}; y=${{x{i}##*/}}; z=${{y/pat/rep}}; "
            "w=$(( {i} + ${{#v}} ))")
    for i in range(n):
        out.append(tmpl.format(i=i))
    return "\n".join(out) + "\n"


def _p_case(cid, title, text, lines):
    return Case(id=cid, title=title, category="parse", kind="process",
                argv=("-n", "{script}"), body=text, iters=lines,
                tags=("parse", "generated"))


CASES = [
    _p_case("parse.n_simple@3000", "parse -n: 3000 simple commands",
            _simple(3000), 3000),
    _p_case("parse.n_funcs@1500", "parse -n: 1500 function definitions",
            _funcs(1500), 1500),
    _p_case("parse.n_control@2000", "parse -n: control/arith corpus",
            _control(2000), 2000),
    _p_case("parse.n_expand@2000", "parse -n: expansion-heavy corpus",
            _expand(2000), 2000),
    _p_case("parse.n_mixed@5000", "parse -n: mixed corpus 5000 lines",
            _simple(2000) + _funcs(1000) + _control(1200) + _expand(800),
            5000),
    Case(id="parse.quote_soup", title="quote-removal heavy word",
         category="parse", tags=("parse",),
         body="x='a'\"b\"\\'c\\''d'\"e\"'f'", iters=8000),
    Case(id="parse.comment_dense", title="script load: comment-dense file",
         category="parse", kind="process", argv=("{script}",),
         body="\n".join("# comment line %d with some words" % i
                        for i in range(3000)) + "\n:\n",
         iters=3000, tags=("parse",)),
    Case(id="parse.long_line", title="script load: one 40k-char line",
         category="parse", kind="process", argv=("-n", "{script}"),
         body="x='" + "a" * 40000 + "'\n", iters=1, tags=("parse",)),
]
