EXPRS = [
    ("plain", "x=$v"),
    ("dollar_brace", "x=${v}"),
    ("quoted", 'x="$v"'),
    ("concat2", "x=a$v"),
    ("concat3", "x=$v$v$v"),
    ("def_colon", "x=${v:-DEF}"),
    ("def_plain", "x=${v-DEF}"),
    ("alt_colon", "x=${v:+ALT}"),
    ("alt_plain", "x=${v+ALT}"),
    ("assign_colon", "x=${v:=DEF}"),
    ("len", "x=${#v}"),
    ("trim_pre1", "x=${v#h}"),
    ("trim_pre2", "x=${v##h*}"),
    ("trim_suf1", "x=${v%o}"),
    ("trim_suf2", "x=${v%%o*}"),
    ("replace1", "x=${v/o/0}"),
    ("replace_all", "x=${v//o/0}"),
    ("replace_pre", "x=${v/#h/H}"),
    ("replace_suf", "x=${v/%o/O}"),
    ("upper1", "x=${v^}"),
    ("upper_all", "x=${v^^}"),
    ("lower1", "x=${v,}"),
    ("lower_all", "x=${v,,}"),
    ("substr_1_2", "x=${v:1:2}"),
    ("substr_2_4", "x=${v:2:4}"),
    ("indirect_name", "x=${!vn}"),
]
for vname, vval in VALUES.items():
    for ename, expr in EXPRS:
        qv = "'" + vval + "'" if (" " in vval or vval == "") else vval
        setup = "v=%s; vn=v" % qv
        add("exp_%s_%s" % (vname, ename), "expand %s on %s" % (ename, vname),
            setup, expr)
        # same operator consumed as a command argument (expansion + argv path)
        body = expr.replace("x=", "echo ", 1) + " >/dev/null"
        add("expw_%s_%s" % (vname, ename), "expand-as-arg %s on %s" % (ename, vname),
            setup, body)
# unset-variable default family (distinct code path)
for expr in ("x=${u:-DEF}", "x=${u-DEF}", "x=${u:+ALT}", "x=${u+ALT}",
             "x=${u:=DEF}", "x=${#u}"):
    add("exp_unset_%d" % (abs(hash(expr)) % 9999), "expand unset %s" % expr[:14],
        "", expr)
# word-level forms
for body, title, setup in (
    ("set -- $v", "unquoted word split", 'v="a b c d"'),
    ("set -- $v$v", "double unquoted split", 'v="a b"'),
    ("x=$v; y=$x", "assign chain", "v=hello"),
    ("x=$((__bs_i+1))", "arith expand assign", ""),
    ("x=`echo hi`", "backquote assign", ""),
    ("echo $v >/dev/null", "expand into echo arg", "v=hello"),
    ("[ $v = hello ]", "expand into test arg", "v=hello"),
    ("[[ $v == h* ]]", "expand into [[ ]] pattern", "v=hello"),
):
    add("exp_word_%d" % (abs(hash(body)) % 9999), title, setup, body)

