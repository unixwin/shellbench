# ---------------------------------------------------------------------------
# Command substitution / process substitution.
# ---------------------------------------------------------------------------
for cmd in ("true", ":", "echo hi", "printf 'x\\n'", "pwd", "cd . && pwd"):
    safe = cmd.replace(" ", "_").replace("'", "").replace("\\", "")[:20]
    add("sub_assign_%s" % safe, "x=$(%s)" % cmd, "", "x=$(%s)" % cmd, N_SLOW)
    add("sub_echo_%s" % safe, "echo $(%s)" % cmd, "", "echo $(%s) >/dev/null" % cmd, N_SLOW)
    add("sub_backq_%s" % safe, "x=`%s`" % cmd, "", "x=`%s`" % cmd, N_SLOW)
add("sub_nested", "x=$(echo $(true))", "", "x=$(echo $(true))", N_SLOW)
