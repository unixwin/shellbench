# ---------------------------------------------------------------------------
# Script-kind replays of field shapes.
# ---------------------------------------------------------------------------
SCRIPT_ROWS = [
    ("while_printf_arith", "while printf %d + ((i++))",
     "i=1\nwhile [ $i -le {iters} ]; do\n    printf '%d\\n' \"$i\"\n    ((i++))\ndone\n"),
    ("while_test_only", "while test + ((i++))",
     "i=1\nwhile [ $i -le {iters} ]; do\n    :\n    ((i++))\ndone\n"),
    ("while_dbracket", "while [[ ]] + ((i++))",
     "i=1\nwhile [[ $i -le {iters} ]]; do\n    :\n    ((i++))\ndone\n"),
    ("for_seq_seq", "for over seq output",
     "for i in $(seq 1 {iters}); do :; done\n"),
    ("read_loop", "read lines loop",
     "while read -r l; do :; done < data.txt\n"),
]


def cases() -> list:
    out = []
    files = (("data.txt", "@gen:lines:100000"),)
    for suffix, title, setup, body, iters, extra in ROWS:
        out.append(Case(
            id="hotloop.%s" % suffix,
            title="hotloop %s" % title, category="hotloop",
            tags=("hotloop", "generated", "v2") + tuple(extra),
            setup=setup, body=body, iters=iters,
            files=files if "data.txt" in body else ()))
    for suffix, title, body in SCRIPT_ROWS:
        out.append(Case(
            id="hotloop.script_%s" % suffix,
            title="hotloop script %s" % title, category="hotloop",
            kind="script", tags=("hotloop", "generated", "v2"),
            body=body, iters=N, files=files))
    return out
